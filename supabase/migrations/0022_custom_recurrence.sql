-- 0022_custom_recurrence.sql · Recurring rules repeat daily, weekly, monthly or yearly (2026-10-12)
--
-- 0020 only knew "day N of every month". A rule now has a start date, a frequency, an interval
-- ("every 2 weeks"), optional weekdays (weekly rules) and an optional end date.
-- A generated entry is identified by the exact date it was due (recurring_date), because a weekly
-- rule makes several entries in one month. The unique key moves from the month to that date, so
-- two phones opening together still never create the same entry twice.
-- start_date stays nullable: phones still running the previous version save rules without it.

alter table public.recurring_rules
  add column frequency    text not null default 'monthly'
    check (frequency in ('daily', 'weekly', 'monthly', 'yearly')),
  add column "interval"   smallint not null default 1 check ("interval" between 1 and 99),
  add column days_of_week smallint[]
    check (days_of_week is null
           or (cardinality(days_of_week) between 1 and 7
               and days_of_week <@ array[0, 1, 2, 3, 4, 5, 6]::smallint[])),
  add column start_date   date,
  add column end_date     date,
  add constraint recurring_rules_dates check (end_date is null or start_date is null or end_date >= start_date);

-- Existing monthly rules: the first due date is day N of the start month (short months clamp).
update public.recurring_rules
set start_date = (start_month || '-01')::date
  + (least(day_of_month,
           extract(day from ((start_month || '-01')::date + interval '1 month - 1 day'))::int) - 1)
where start_date is null;

alter table public.transactions add column recurring_date date;

-- Entries already generated by a monthly rule were due on day N of their month.
update public.transactions t
set recurring_date = (t.recurring_month || '-01')::date
  + (least(r.day_of_month,
           extract(day from ((t.recurring_month || '-01')::date + interval '1 month - 1 day'))::int) - 1)
from public.recurring_rules r
where r.id = t.recurring_rule_id
  and t.recurring_month is not null
  and t.recurring_date is null;

alter table public.transactions
  add constraint transactions_recurring_pair
    check (recurring_date is null or recurring_rule_id is not null);

alter table public.transactions drop constraint transactions_recurring_month_uniq;
alter table public.transactions
  add constraint transactions_recurring_date_uniq unique (household_id, recurring_rule_id, recurring_date);
